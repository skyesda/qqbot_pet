def _gen_province_capital() -> list[dict[str, Any]]:
    """省/自治区/特别行政区：行政中心在哪。直辖市与港澳的行政中心与本身同名，跳过。"""
    rows = []
    province_names = [n for n, _c, _a, _r in _PROVINCES if n.endswith("省")]
    capitals = [c for _n, c, _a, _r in _PROVINCES]
    for name, capital, _abbr, _region in _PROVINCES:
        if capital in name:  # 北京/上海/天津/重庆/香港/澳门
            continue
        if name.endswith("自治区"):
            rows.append(_mk(f"{name}的首府是哪座城市？", capital,
                            _sample(capitals, capital), 2, _NAT))
        else:
            rows.append(_mk(f"{name}的省会是哪座城市？", capital,
                            _sample(capitals, capital), 2, _NAT))
    # 反向：城市 → 省级行政区（干扰项限定在同一类里，才有迷惑性）
    for name, capital, _abbr, _region in _PROVINCES:
        if capital in name:
            continue
        if name.endswith("自治区"):
            pool = [n for n, _c, _a, _r in _PROVINCES if n.endswith("自治区")]
            rows.append(_mk(f"{capital}是哪个自治区的首府？", name, _sample(pool, name), 2, _NAT))
        else:
            rows.append(_mk(f"{capital}是哪个省的省会？", name,
                            _sample(province_names, name), 2, _NAT))
    return rows


def _gen_province_abbr() -> list[dict[str, Any]]:
    """省级行政区简称。34 个简称互不重复，可整体当候选池。"""
    abbrs = [a for _n, _c, a, _r in _PROVINCES]
    return [_mk(f"{name}的简称是什么？", abbr, _sample(abbrs, abbr), 2, _NAT)
            for name, _c, abbr, _r in _PROVINCES]


def _gen_province_region() -> list[dict[str, Any]]:
    """省级行政区属于哪个地理分区（七大地理分区）。"""
    return [_mk(f"{name}位于我国哪个地理分区？", region, _sample(_REGIONS, region), 2, _NAT)
            for name, _c, _a, region in _PROVINCES]


