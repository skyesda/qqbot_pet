"""「月耀华诞」华诞巡礼题库：本地文化常识单选题（1000+ 道）。

字段与 puzzles.py 的 _QUIZ 完全一致（q/options/answer/answer_type/difficulty/theme），
区别在于这里是「结构化事实表 + 生成器」而不是手写字面量：每行事实直接给出正确答案，
题干由模板拼成通顺问句，因此答案天然自洽、不会写错，也方便扩题。

主题划分：
- theme="national"：国庆与国家象征、省级行政区、地理、历史、城市、航天与科技成就；
- theme="midautumn"：中秋与月亮、二十四节气、传统节日、古典文学、诗词、
  生肖干支、京剧书法国画等传统文化。

难度：1=常识级 2=中学级 3=较难。

确定性：抽干扰项与打乱选项全部走模块私有的 _RNG（固定种子），不碰全局 random
—— puzzles.local_lantern() 用的是全局 random 抽灯谜，两者不能互相污染，
且固定种子保证每次 import 出来的题库内容与顺序都一致（可复现、可校验）。
"""
from __future__ import annotations

import random
from typing import Any

_RNG = random.Random(20260929)

_NAT = "national"
_MID = "midautumn"


def _sample(pool, answer: str, n: int = 3) -> list[str]:
    """从同类别候选池里抽 n 个不同于答案的干扰项（先去重，保证稳定可复现）。"""
    uniq = [str(x) for x in dict.fromkeys(pool) if str(x) != answer]
    return _RNG.sample(uniq, n)


def _mk(q: str, answer: str, distractors, difficulty: int, theme: str) -> dict[str, Any]:
    """拼一道题：干扰项去重取 3 个 + 正确答案，再用固定种子打乱选项顺序。"""
    answer = str(answer)
    wrong: list[str] = []
    for d in distractors:
        d = str(d)
        if d != answer and d not in wrong:
            wrong.append(d)
        if len(wrong) == 3:
            break
    if len(wrong) != 3:
        raise ValueError("干扰项不足：" + q)
    options = wrong + [answer]
    _RNG.shuffle(options)
    return {"q": q, "options": options, "answer": answer,
            "answer_type": "str", "difficulty": difficulty, "theme": theme}


def _from_facts(rows) -> list[dict[str, Any]]:
    """事实表 → 题目。每行是 (题干, 正确答案, 干扰项列表, 难度, 主题)。"""
    return [_mk(q, ans, dis, diff, theme) for q, ans, dis, diff, theme in rows]


