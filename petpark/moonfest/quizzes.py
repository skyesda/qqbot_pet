def _gen_solar_terms() -> list[dict[str, Any]]:
    """节气：所属季节 / 下一个节气 / 由含义反查节气。"""
    names = [t for t, _s, _m in _SOLAR_TERMS]
    rows = []
    for i, (term, season, meaning) in enumerate(_SOLAR_TERMS):
        rows.append(_mk(f"「{term}」是哪个季节的节气？", season,
                        _sample(_SEASONS, season), 1, _MID))
        if i % 4 == 0:  # 节气顺序题隔三个出一题
            nxt = _SOLAR_TERMS[(i + 1) % len(_SOLAR_TERMS)][0]
            rows.append(_mk(f"二十四节气中，「{term}」之后的下一个节气是什么？", nxt,
                            _sample(names, nxt), 2, _MID))
        # 春分/秋分含义相近只当干扰项；含义题隔一个出一题
        if term not in ("春分", "秋分") and i % 2 == 0:
            rows.append(_mk(f"二十四节气中，表示「{meaning}」的是哪个节气？", term,
                            _sample(names, term), 3, _MID))
    return rows


