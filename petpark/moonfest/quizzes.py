def _gen_festivals() -> list[dict[str, Any]]:
    """节日：日期（正反）/ 别称 / 传统食品 / 传统习俗（正反两向）。"""
    names = [f["name"] for f in _FESTIVALS]
    dates = [f["date"] for f in _FESTIVALS]
    all_customs = [c for f in _FESTIVALS for c in f["customs"]]
    rows = []
    for fest in _FESTIVALS:
        name = fest["name"]
        rows.append(_mk(f"{name}的日期是下列哪一项？", fest["date"],
                        _sample(dates, fest["date"]), 1, _MID))
        # 清明按公历、除夕是腊月最后一天，反查题不成立
        if not fest["date"].startswith("公历") and "最后一天" not in fest["date"]:
            rows.append(_mk(f"农历{fest['date']}是哪个传统节日？", name,
                            _sample(names, name), 1, _MID))
        for alias in fest["aliases"][:1]:  # 别称取主用那一个，够用且不堆量
            rows.append(_mk(f"「{alias}」是哪个传统节日的别称？", name,
                            _sample(names, name), 2, _MID))
        for food in fest["foods"]:
            rows.append(_mk(f"「{food}」是哪个传统节日的传统食品？", name,
                            _sample(names, name), 1, _MID))
        others = [c for c in all_customs if c not in fest["customs"]]
        for i, custom in enumerate(fest["customs"]):
            if i == 0:  # 正向题一节日只出一道（题干里带节日名，天然不重复）
                rows.append(_mk(f"下列哪一项是{name}的传统习俗？", custom,
                                _sample(others, custom), 2, _MID))
            if i < 1:  # 反查题每节日只出主打那一条
                rows.append(_mk(f"「{custom}」是哪个传统节日的习俗？", name,
                                _sample(names, name), 2, _MID))
    return rows


