def _cn_index(i: int) -> str:
    """1 → 一，11 → 十一，12 → 十二。"""
    if i <= 10:
        return _CN_NUM[i - 1]
    return "十" + _CN_NUM[i - 11]


def _gen_zodiac() -> list[dict[str, Any]]:
    """十二生肖：顺序、名次、前后相邻。"""
    rows = []
    for i, animal in enumerate(_ZODIAC):
        rows.append(_mk(f"十二生肖中，排在第{_cn_index(i + 1)}位的是哪种动物？", animal,
                        _sample(_ZODIAC, animal), 1, _MID))
        if i % 2 == 0:  # 名次题隔一个出一题
            rows.append(_mk(f"「{animal}」在十二生肖中排第几位？", str(i + 1),
                            _sample([str(x) for x in range(1, 13)], str(i + 1)), 2, _MID))
    for i, animal in enumerate(_ZODIAC):
        nxt = _ZODIAC[(i + 1) % 12]
        rows.append(_mk(f"十二生肖中，排在「{animal}」后面的是哪种动物？", nxt,
                        _sample(_ZODIAC, nxt), 2, _MID))
    return rows


