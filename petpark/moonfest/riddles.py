"""「月耀华诞」中秋段「猜灯谜」的本地灯谜题库（≥1000 条）。

为什么单独开一个文件：puzzles.py 里的 _LANTERNS 只有十几条，是给活动兜底用的
样例；灯谜要撑起整晚的玩法，得有足够大的池子。这里用「结构化表 + 生成器」而不是
1000 条字面量 dict，好处是文件小、谜底由数据行决定（拆字表写错一眼能看出来）、
后期加谜只需往表里加一行。

数据分三层：
- _MOON/_GUI/... 等字面量列表：手写经典灯谜，每条 (谜面, 谜底, 提示)；
- _COMPOUND 等表：拆字/减字表，(结构, 部件A, 部件B, 谜底, 释义, 会意谜面, 主题)，
  由 _gen_*() 套多种句式生成，句式随条目轮转，避免一水儿的「X加Y」；
- all_lanterns()：拼起来去重后返回，字段与 puzzles.py 的 _LANTERNS 完全一致。

两条硬约定（改数据时必须守住）：
1. 谜面全局唯一——all_lanterns() 会按谜面去重兜底，但表本身也别写成重复的；
2. 提示里不许出现谜底字符串（包括谜底字嵌在别的词里，比如谜底「日」而提示写了
   「日月同辉」），否则玩家看提示就能抄答案。tools 里跑校验脚本会逐条查。
"""

