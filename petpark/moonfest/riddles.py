def _iter_compound() -> list[tuple[str, str, str, str]]:
    """展开拆字表为 (谜面, 谜底, 提示, 主题)。"""
    out: list[tuple[str, str, str, str]] = []
    tip_cache = _STRUCT_TIP
    for idx, (struct, a, b, ans, gloss, imagery, theme) in enumerate(_COMPOUND):
        tpls = _compound_templates(struct, a, b)
        if not tpls:  # 表里结构写错了要立刻炸，而不是悄悄少几条谜
            raise ValueError(f"未知结构 {struct!r}：{a}+{b}")
        hint = f"{gloss}（{tip_cache[struct]}）"
        # 有会意谜面的先用它，再按条目序号轮转取句式：相邻条目句式不重样，
        # 整个题库读起来才不像同一条模板刷出来的。
        want = 2 if imagery else 3
        phrasings = ([imagery] if imagery else []) + [
            tpls[(idx + k) % len(tpls)] for k in range(min(want, len(tpls)))
        ]
        for p in phrasings:
            if p.endswith("，打一字"):
                p = p[: -len("，打一字")]
            if ans in p:
                continue
            out.append((f"{p}（打一字）", ans, hint, theme))
    return out


def _iter_literal() -> list[tuple[str, str, str, str]]:
    pairs: list[tuple[list[tuple[str, str, str]], str]] = [
        (_MOON, "月"),
        (_GUI, "桂"),
        (_TU, "兔"),
        (_DENG, "灯"),
        (_MOONCAKE, "月饼"),
        (_ZHONGQIU, "中秋"),
        (_GUOQING, "国庆"),
        (_ZIMI, "字谜"),
        (_CHENGYU, "成语"),
        (_WUMI, "物谜"),
    ]
    out: list[tuple[str, str, str, str]] = []
    for rows, theme in pairs:
        for q, ans, hint in rows:
            out.append((q, ans, hint, theme))
    out.extend(_EXTRA)
    return out


